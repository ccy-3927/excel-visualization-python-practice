        rows=list(book.active.values);book.close()
        h=next(i for i,r in enumerate(rows) if str(r[0]).strip()=='指标')
        years=[int(str(v)[:4]) for v in rows[h][1:]]
        for row in rows[h+1:]:
            text=str(row[0] or '').strip();match=re.match(r'(.+)\s+\(([^()]+)\)\s*$',text)
