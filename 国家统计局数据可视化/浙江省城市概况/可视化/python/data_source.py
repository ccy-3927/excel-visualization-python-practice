def load_data(data_dir=None):
    """读取内嵌快照，或读取指定目录的原始 xlsx；不修改源文件。"""
    if data_dir is None:
        return json.loads(json.dumps(SNAPSHOT, ensure_ascii=False))
    import openpyxl
    import hashlib
    result = {'series': {}, 'notes': {}, 'sha256': {}}
    for filename in SNAPSHOT['sha256']:
        path = Path(data_dir) / filename
        book = openpyxl.load_workbook(path, read_only=True, data_only=True)
        rows = list(book.active.values)
        if '浙江省' not in str(rows[1][0]):
            raise ValueError(f'{filename} 地区不是浙江省，请核对。')
        header = next(i for i, row in enumerate(rows) if str(row[0]).strip() == '指标')
        years = [int(str(v)[:4]) for v in rows[header][1:] if v is not None]
        if any(y not in YEARS for y in years):
            raise ValueError('新数据包含2016—2024之外的年份，需同步修改图表时间轴。')
        topic = path.stem
        result['notes'][topic] = []
        for row in rows[header + 1:]:
            text = str(row[0] or '').strip()
            match = re.match(r'(.+?)\s*\((.+?)\)\s*$', text)
            if match:
                name, unit = match.groups()
                values = {str(y): None if v in ('', None) else float(v) for y, v in zip(years, row[1:])}
                result['series'][name.strip()] = dict(topic=topic, unit=unit, values=values)
